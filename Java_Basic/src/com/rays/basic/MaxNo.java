package com.rays.basic;

public class MaxNo {

	public static void main(String[] args) {

		int a = 10;
		int b = 10;

		if (a == b) {
			System.out.println("both no are equals");
		} else if (a > b) {
			System.out.println("A is Max no : " + a);
		} else {
			System.out.println("b is Max no :" + b);
		}

	}

}
